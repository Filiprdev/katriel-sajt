/**
 * Bilingual site: English at /, Serbian (Latin script) at /sr/.
 * All interface text lives here. Page bodies use `const { t, lang, path } = useI18n(Astro)`.
 */
export const languages = { en: 'English', sr: 'Srpski' } as const;
export type Lang = keyof typeof languages;
export const defaultLang: Lang = 'en';

/** Locale for Intl (prices, dates) and og:locale. */
export const intlLocale: Record<Lang, string> = { en: 'en-IE', sr: 'sr-Latn-RS' };
export const ogLocale: Record<Lang, string> = { en: 'en_US', sr: 'sr_RS' };

/** '/shop/' → '/sr/shop/' for Serbian. External links and '#' pass through. */
export function localizePath(path: string, lang: Lang): string {
  if (!path.startsWith('/') || lang === defaultLang) return path;
  return `/${lang}${path}`;
}

/** Strip the language prefix: '/sr/shop/' → '/shop/'. */
export function basePath(pathname: string): string {
  return pathname.replace(/^\/sr(?=\/|$)/, '') || '/';
}

/** Serbian plural: 1 komad, 2–4 komada, 5+ komada (21 komad, 11–14 komada). */
export function plural(lang: Lang, n: number, forms: { one: string; few: string; many: string }): string {
  if (lang === 'en') return n === 1 ? forms.one : forms.many;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms.one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms.few;
  return forms.many;
}

