export const ui: Record<Lang, Dict> = { en, sr };

/** Use in any .astro file: `const { t, lang, l, path } = useI18n(Astro);` */
export function useI18n(astro: { currentLocale?: string; url: URL }) {
  const lang = (astro.currentLocale === 'sr' ? 'sr' : 'en') as Lang;
  return {
    lang,
    t: ui[lang],
    /** Localize an internal path. */
    l: (path: string) => localizePath(path, lang),
    /** Current path without language prefix. */
    path: basePath(astro.url.pathname),
  };
}
